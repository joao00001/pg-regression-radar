// TestMathPageMatchesEngine keeps the docs' "Our math" page honest. Every
// figure on that page runs docs/assets/math/math-core.js, a port of this
// package's change-point and t-test code. The fixtures were generated by that
// module (testdata/gen_mathpage_fixtures.js); the real engine must reach the
// same verdict, factor, change point and p-value on every one.
func TestMathPageMatchesEngine(t *testing.T) {
	raw, err := os.ReadFile("testdata/mathpage_fixtures.json")
	if err != nil {
		t.Fatal(err)
	}
	var in struct {
		Fixtures []struct {
			WindowMin int `json:"windowMin"`
			Cfg       struct {
				LatencyThreshold float64 `json:"latencyThreshold"`
				PThreshold       float64 `json:"pThreshold"`
				MinSamples       int64   `json:"minSamples"`
				MinExecutions    int64   `json:"minExecutions"`
				ToleranceMin     float64 `json:"toleranceMin"`
			} `json:"cfg"`
			Samples []struct {
				T       float64 `json:"t"`
				Calls   int64   `json:"calls"`
				TotalMs float64 `json:"totalMs"`
			} `json:"samples"`
			Expected struct {
				Verdict     string   `json:"verdict"`
				Factor      float64  `json:"factor"`
				P           *float64 `json:"p"`
				ChangeAtMin *float64 `json:"changeAtMin"`
			} `json:"expected"`
		} `json:"fixtures"`
		Tgrid []struct {
			Df, T, P float64
		} `json:"tgrid"`
	}
	if err := json.Unmarshal(raw, &in); err != nil {
		t.Fatal(err)
	}
	if len(in.Fixtures) == 0 {
		t.Fatal("no fixtures")
	}

	deploy := time.Date(2026, 1, 1, 12, 0, 0, 0, time.UTC)
	for i, f := range in.Fixtures {
		e := New(Config{
			WindowMinutes:          f.WindowMin,
			MinSamples:             f.Cfg.MinSamples,
			MinExecutions:          f.Cfg.MinExecutions,
			LatencyChangeThreshold: f.Cfg.LatencyThreshold,
			PValueThreshold:        f.Cfg.PThreshold,
			ChangePointTolerance:   time.Duration(f.Cfg.ToleranceMin * float64(time.Minute)),
		}, nil, slog.New(slog.NewTextHandler(io.Discard, nil)))
		var samples []pgstat.QuerySample
		for _, s := range f.Samples {
			samples = append(samples, pgstat.QuerySample{
				QueryID:         1,
				RecordedAt:      deploy.Add(time.Duration(s.T * float64(time.Minute))),
				IntervalKnown:   true,
				IntervalCalls:   s.Calls,
				IntervalTotalMs: s.TotalMs,
				IntervalMeanMs:  s.TotalMs / float64(s.Calls),
			})
		}
		pre, post := partitionAt(samples, deploy)
		r := e.evaluateQuery(v1alpha1.DeployEvent{ID: "x", Timestamp: deploy}, 1, pre, post)

		if string(r.Status) != f.Expected.Verdict {
			t.Errorf("fixture %d: verdict %s, page says %s", i, r.Status, f.Expected.Verdict)
			continue
		}
		if f.Expected.Factor != 0 && math.Abs(r.LatencyChangeFactor-f.Expected.Factor) > 1e-9*f.Expected.Factor {
			t.Errorf("fixture %d: factor %v, page says %v", i, r.LatencyChangeFactor, f.Expected.Factor)
		}
		st := e.computeChangeStats(1, pre, post)
		if f.Expected.ChangeAtMin != nil {
			if !st.changePointFound {
				t.Errorf("fixture %d: no change point, page found one at %v min", i, *f.Expected.ChangeAtMin)
			} else if d := math.Abs(st.changeAt.Sub(deploy).Minutes() - *f.Expected.ChangeAtMin); d > 1e-6 {
				t.Errorf("fixture %d: change point %v min off the page's", i, d)
			}
		}
		if f.Expected.P != nil {
			if !st.changePointFound {
				t.Errorf("fixture %d: no p-value, page says %v", i, *f.Expected.P)
			} else if math.Abs(st.pValue-*f.Expected.P) > 1e-9 {
				t.Errorf("fixture %d: p %v, page says %v", i, st.pValue, *f.Expected.P)
			}
		}
	}
	for _, g := range in.Tgrid {
		if got := tDistPValue(g.T, g.Df); math.Abs(got-g.P) > 1e-9 {
			t.Errorf("tDistPValue(%v, %v) = %v, page says %v", g.T, g.Df, got, g.P)
		}
	}
}
