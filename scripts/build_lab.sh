#!/usr/bin/env bash
# Regenerates examples/lab/00-radar.yaml: the namespace plus the Helm chart
# (manager mode, CRDs included) rendered as plain manifests, so the lab can be
# started with `kubectl apply -f` and no Helm.
#
#   scripts/build_lab.sh            # rewrite the file
#   scripts/build_lab.sh --check    # fail if the checked-in file is stale (CI)
#
# LAB_IMAGE_TAG picks the manager image tag baked into the file (default
# "latest", the newest release).
set -euo pipefail

cd "$(dirname "$0")/.."

TAG="${LAB_IMAGE_TAG:-latest}"
OUT="examples/lab/00-radar.yaml"
MODE="${1:-write}"

command -v helm >/dev/null || { echo "helm is required (https://helm.sh/docs/intro/install/)" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Package first so the rendered labels carry a lab version instead of the
# placeholder checked into Chart.yaml.
helm package deploy/helm/deploylens --version 0.0.0-lab --app-version "$TAG" --destination "$tmp" >/dev/null

{
  cat <<HEADER
# pg-regression-radar lab — step 1 of 3: the radar itself.
#
# GENERATED by scripts/build_lab.sh from deploy/helm/deploylens; do not edit by
# hand. It contains the pgrr-lab namespace, the four CRDs, the manager's RBAC
# and the manager Deployment (image tag: ${TAG}), with a single replica and no
# leader election because this is a throwaway lab.
apiVersion: v1
kind: Namespace
metadata:
  name: pgrr-lab
---
HEADER
  helm template pgrr "$tmp/pg-regression-radar-0.0.0-lab.tgz" \
    --namespace pgrr-lab --include-crds \
    --set mode=manager \
    --set fullnameOverride=pgrr \
    --set manager.image.tag="$TAG" \
    --set manager.replicaCount=1 \
    --set manager.leaderElection.enabled=false \
    --set manager.createDefaultWatch=false
} > "$tmp/raw.yaml"

# `helm template --namespace` does not stamp metadata.namespace on the objects,
# so without this step `kubectl apply -f` would create them in whatever
# namespace is current instead of pgrr-lab. Add it to every namespaced object
# that lacks one.
python3 - "$tmp/raw.yaml" > "$tmp/out.yaml" <<'PY'
import re, sys

NAMESPACED = {"ServiceAccount", "Secret", "Service", "Deployment", "Role", "RoleBinding", "ConfigMap"}
docs = open(sys.argv[1]).read().split("\n---\n")
out = []
for doc in docs:
    kind = re.search(r"^kind: (\S+)", doc, re.M)
    if kind and kind.group(1) in NAMESPACED:
        meta = re.search(r"^metadata:\n((?:  .*\n)+)", doc + "\n", re.M)
        if meta and not re.search(r"^  namespace:", meta.group(1), re.M):
            doc = re.sub(r"^(metadata:\n  name: .*)$", r"\1\n  namespace: pgrr-lab", doc, count=1, flags=re.M)
            assert "namespace: pgrr-lab" in doc, "could not add a namespace to a " + kind.group(1)
    out.append(doc)
sys.stdout.write("\n---\n".join(out))
PY

if [ "$MODE" = "--check" ]; then
  if ! diff -u "$OUT" "$tmp/out.yaml"; then
    echo "::error::$OUT is stale. Run scripts/build_lab.sh and commit the result." >&2
    exit 1
  fi
  echo "$OUT is up to date."
else
  cp "$tmp/out.yaml" "$OUT"
  echo "wrote $OUT"
fi
